let _debugLocale = null;
let _origTranslate = null;

export function setDebugLocale(locale) {
    _debugLocale = locale;
}

export function initI18n(extensionObject) {
    try {
        if (extensionObject && typeof extensionObject.gettext === 'function')
            _origTranslate = extensionObject.gettext.bind(extensionObject);
    } catch (_) {}
}

export function getLocale() {
    if (_debugLocale) return _debugLocale;
    try {
        const langs = GLib.get_language_names();
        for (const l of langs) {
            if (!l || l === 'C' || l === 'POSIX') continue;
            const code = l.split('.')[0].split('_')[0].split('-')[0].toLowerCase();
            if (code && TRANSLATIONS[code]) {
                return code;
            }
        }
    } catch (_) {}
    return 'en';
}

function _cleanLabel(str) {
    if (!str || typeof str !== 'string') return '';
    return str
        .replace(/_/g, '')
        .replace(/&/g, '')
        .replace(/\s*\([A-Za-z0-9]\)$/g, '')
        .trim();
}

export function _(str) {
    if (!str || typeof str !== 'string') return str;
    const lang = getLocale();
    if (lang === 'en') return str;

    const dict = TRANSLATIONS[lang];
    if (!dict) return str;

    // 1. Direct exact match
    if (dict[str] !== undefined) {
        return dict[str];
    }

    // 2. Cleaned / normalized match (strip underscores, accelerators)
    const clean = _cleanLabel(str);
    if (dict[clean] !== undefined) {
        return dict[clean];
    }

    // 3. Normalized without trailing ellipsis
    const withoutDots = clean.replace(/\.{3}$|…$/g, '').trim();
    if (dict[withoutDots] !== undefined) {
        const hasEllipsis = str.endsWith('...') || str.endsWith('…');
        return hasEllipsis ? dict[withoutDots] + '…' : dict[withoutDots];
    }

    // 4. Case-insensitive lookup
    const lower = clean.toLowerCase();
    for (const [k, v] of Object.entries(dict)) {
        if (k.toLowerCase() === lower) {
            return v;
        }
    }

    // 5. Fallback to gettext domain
    if (_origTranslate) {
        try {
            const res = _origTranslate(str);
            if (res && res !== str) return res;
        } catch (_) {}
    }

    return str;
}
