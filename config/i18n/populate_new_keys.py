def main():
    print("Loading translations_data.py...")
    import sys
    sys.path.insert(0, os.path.join(REPO_ROOT, "config/i18n"))
    import translations_data

    translations = translations_data.TRANSLATIONS
    rtl = translations_data.RTL_LANGUAGES

    all_langs = list(translations.keys())
    print(f"Total languages in TRANSLATIONS: {len(all_langs)}")

    placeholder_re = re.compile(r"\{([a-zA-Z0-9_]+)\}")

    # Add each key
    for key, lang_map in NEW_KEYS_DATA.items():
        en_val = lang_map["en"]
        en_placeholders = set(placeholder_re.findall(en_val))

        for lang in all_langs:
            if lang in lang_map:
                val = lang_map[lang]
            else:
                rel = RELATIVES_MAP.get(lang, "en")
                val = lang_map.get(rel, en_val)

            # Ensure exact placeholder matching
            lang_placeholders = set(placeholder_re.findall(val))
            if lang_placeholders != en_placeholders:
                # If relative language corrupted placeholders, fall back to en_val
                val = en_val

            translations[lang][key] = val

    # Verify consistency across all 58 languages
    en_keys = set(translations["en"].keys())
    for lang, d in translations.items():
        missing = en_keys - set(d.keys())
        if missing:
            raise RuntimeError(f"Language {lang} is missing keys: {missing}")
        for k, v in d.items():
            en_ph = set(placeholder_re.findall(translations["en"][k]))
            l_ph = set(placeholder_re.findall(v))
            if en_ph != l_ph:
                raise RuntimeError(f"Placeholder mismatch in {lang}:{k}: {en_ph} != {l_ph}")

    print(f"Successfully validated all {len(en_keys)} keys across all {len(translations)} languages!")

    # Write back to translations_data.py
    with open(DATA_PY, "w", encoding="utf-8") as f:
        f.write("# SPDX-License-Identifier: GPL-3.0-or-later\n")
        f.write(f"RTL_LANGUAGES = {repr(rtl)}\n\n")
        f.write("TRANSLATIONS = " + json.dumps(translations, ensure_ascii=False, indent=4) + "\n")

    print(f"Updated {DATA_PY}")

if __name__ == "__main__":
    main()
